# колбек при кліку — фарбує клітинку
def on_point(x, y):
    lin = pic.serialize_cells()
    idx = y * 24 + x
    c = lin[idx]
    c["color"] = 0xFFFF66
    c["symbol"] = "·"
    lin[idx] = c
    mat = [lin[i * 24:(i + 1) * 24] for i in range(24)]
    pic.set_input(mat)
    root.title(f"Clicked: ({x},{y})")

pic.set_on_point(on_point)

root.mainloop()
